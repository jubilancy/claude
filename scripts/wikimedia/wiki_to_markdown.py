"""
wiki_to_markdown.py — pull full Wikimedia articles into clean, frontmatter-rich
Obsidian-safe markdown files.

What it does:
- Reads a list of wiki URLs from urls.txt (one per line, # comments ok)
- Fetches each article from the wiki it actually lives on (en.wikipedia.org,
  en.wikibooks.org, en.wikisource.org, etc.) via action=parse, which returns
  every section, and un-collapses MediaWiki collapsible boxes so nothing hidden
  behind a click-to-expand toggle is lost.
- Skips files that already exist BEFORE making any network request. The check looks in
  subfolders too, so it still works after sort_markdown.py has sorted the corpus.
- Skips Special: pages up front (they are generated, not real articles).
- Retries on 429/503, honoring the Retry-After header when present.
- Converts to Markdown with markdownify, with frontmatter (title, description,
  source, categories, tags, retrieved date, word count) and Obsidian footnotes.
- Files from non-English-Wikipedia wikis get a suffix so they don't overwrite
  each other, e.g. "Literature (wikibooks).md".
- Writes results-log-{timestamp}.txt in the current folder every run, with
  separate lists for written, skipped, and errors, plus warnings.

Usage:
    uv run scripts/wikimedia/wiki_to_markdown.py                  # reads ./urls.txt, writes ./corpus/
    uv run scripts/wikimedia/wiki_to_markdown.py --input other.txt --output out_dir
    uv run scripts/wikimedia/wiki_to_markdown.py --force          # re-download even if file exists

Log line for Obsidian:
    uv run scripts/wikimedia/wiki_to_markdown.py  # pulls full wiki articles from urls.txt into
    frontmatter-rich markdown files in corpus/, skips existing files and Special:
    pages, retries on rate limits, writes results-log-{timestamp}.txt each run
"""

import argparse
import glob
import re
import sys
import time
import unicodedata
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import parse_qs, quote, unquote, urlparse

import requests
import yaml
from bs4 import BeautifulSoup, NavigableString
from markdownify import MarkdownConverter

KEEP_NAVBOXES = True  # set False to drop navbox tables at the bottom of articles

USER_AGENT = "wiki-corpus-builder/1.0 (personal markdown archive; contact via GitHub)"
REQUEST_DELAY_SECONDS = 1.0  # polite pause after each URL that hit the network
MAX_RETRIES = 5  # retries on 429/503 before giving up on a request
RETRY_BASE_SECONDS = 5.0  # first backoff wait; doubles each retry
RETRY_MAX_WAIT_SECONDS = 120.0  # cap on any single wait


class SkipUrl(Exception):
    """Raised for URLs that should be skipped on purpose (not errors)."""


# --------------------------------------------------------------------------
# HTTP helper with retry
# --------------------------------------------------------------------------

def get_with_retry(url: str, *, params=None, timeout: int = 30, max_retries: int = MAX_RETRIES):
    """GET with retry on 429/503. Honors a numeric Retry-After header."""
    delay = RETRY_BASE_SECONDS
    for attempt in range(max_retries + 1):
        resp = requests.get(
            url, params=params, headers={"User-Agent": USER_AGENT}, timeout=timeout
        )
        if resp.status_code in (429, 503) and attempt < max_retries:
            retry_after = resp.headers.get("Retry-After", "")
            wait = float(retry_after) if retry_after.isdigit() else delay
            wait = min(wait, RETRY_MAX_WAIT_SECONDS)
            print(f"  HTTP {resp.status_code}, waiting {wait:.0f}s (retry {attempt + 1}/{max_retries})")
            time.sleep(wait)
            delay *= 2
            continue
        resp.raise_for_status()
        return resp


# --------------------------------------------------------------------------
# URL parsing / API helpers
# --------------------------------------------------------------------------

def parse_wiki_url(url: str):
    """Extract (host, title) from a wiki article URL."""
    parsed = urlparse(url.strip())
    host = parsed.netloc.lower().replace(".m.", ".")  # en.m.wikipedia.org -> en.wikipedia.org

    path = parsed.path
    title = None
    if "/wiki/" in path:
        title = path.split("/wiki/", 1)[1]
    else:
        qs = parse_qs(parsed.query)
        if "title" in qs:
            title = qs["title"][0]

    if not host or not title:
        raise ValueError(f"Could not extract host and article title from URL: {url}")

    title = unquote(title).replace("_", " ")
    return host, title


def check_not_special(title: str) -> None:
    if re.match(r"^special:", title, re.I):
        raise SkipUrl("Special: page (generated by MediaWiki, not a real article)")


def file_suffix(host: str) -> str:
    """'' for en.wikipedia.org; otherwise ' (wikibooks)' or ' (de.wikipedia)'."""
    parts = host.split(".")
    if len(parts) < 3:
        return f" ({host})"
    lang, project = parts[0], parts[1]
    if lang == "en" and project == "wikipedia":
        return ""
    if lang == "en":
        return f" ({project})"
    return f" ({lang}.{project})"


def fetch_full_html(host: str, title: str):
    """
    Fetch the FULL parsed article HTML via action=parse on the article's own wiki.
    Returns (html, categories, display_title).
    """
    api_url = f"https://{host}/w/api.php"
    params = {
        "action": "parse",
        "page": title,
        "prop": "text|categories|displaytitle",
        "format": "json",
        "formatversion": "2",
        "redirects": "1",
    }
    resp = get_with_retry(api_url, params=params, timeout=30)
    data = resp.json()

    if "error" in data:
        raise RuntimeError(f"Wiki API error for '{title}' on {host}: {data['error']}")

    parse_data = data["parse"]
    html = parse_data["text"]
    categories = [c["category"].replace("_", " ") for c in parse_data.get("categories", [])]
    display_title = parse_data.get("displaytitle", title)
    display_title = BeautifulSoup(display_title, "html.parser").get_text()

    return html, categories, display_title


def fetch_description(host: str, title: str):
    """
    Short description via the REST summary endpoint (frontmatter only, never body).
    Returns (description, ok). ok is False if the lookup failed for a reason other
    than the page simply having no summary (404), so the log can flag it.
    """
    rest_url = f"https://{host}/api/rest_v1/page/summary/{quote(title.replace(' ', '_'), safe='')}"
    try:
        resp = get_with_retry(rest_url, timeout=15, max_retries=2)
        data = resp.json()
        return (data.get("description") or data.get("extract", "")[:200]), True
    except requests.HTTPError as e:
        if e.response is not None and e.response.status_code == 404:
            return "", True
        return "", False
    except (requests.RequestException, ValueError):
        return "", False


# --------------------------------------------------------------------------
# HTML cleanup — uncollapse everything, strip chrome, keep real content
# --------------------------------------------------------------------------

def uncollapse_and_clean(html: str, base_url: str, keep_navboxes: bool = True):
    soup = BeautifulSoup(html, "html.parser")

    # 1. Un-collapse every MediaWiki collapsible box so hidden content survives.
    for el in soup.find_all(class_=re.compile(r"\bmw-collapsible\b|\bcollapsible\b")):
        classes = el.get("class", [])
        el["class"] = [
            c for c in classes
            if c not in ("mw-collapsed", "collapsed", "mw-collapsible", "collapsible")
        ]
        style = el.get("style", "")
        if style:
            style = re.sub(r"display\s*:\s*none\s*;?", "", style, flags=re.I)
            el["style"] = style

    for el in soup.find_all(class_=re.compile(r"mw-collapsible-content")):
        style = el.get("style", "")
        style = re.sub(r"display\s*:\s*none\s*;?", "", style, flags=re.I)
        el["style"] = style

    # 2. Remove edit-section links ("[edit]").
    for el in soup.find_all("span", class_="mw-editsection"):
        el.decompose()

    # 3. Remove reference-list backlink caret artifacts.
    for el in soup.find_all("a", class_="mw-cite-backlink"):
        el.decompose()

    # 4. Drop pure-chrome elements.
    for el in soup.find_all(id="toc"):
        el.decompose()
    for el in soup.find_all("span", class_="mw-headline-anchor"):
        el.decompose()

    # 5. Optionally drop navboxes.
    if not keep_navboxes:
        for el in soup.find_all("table", class_=re.compile(r"navbox")):
            el.decompose()

    # 6. Resolve every image src to an absolute URL (src, data-src, srcset).
    for img in soup.find_all("img"):
        for attr in ("src", "data-src"):
            val = img.get(attr)
            if val and val.startswith("//"):
                img[attr] = "https:" + val
            elif val and val.startswith("/"):
                img[attr] = base_url + val
        srcset = img.get("srcset")
        if srcset:
            fixed_parts = []
            for part in srcset.split(","):
                part = part.strip()
                if part.startswith("//"):
                    part = "https:" + part
                elif part.startswith("/"):
                    part = base_url + part
                fixed_parts.append(part)
            img["srcset"] = ", ".join(fixed_parts)

    # 7. Convert inline citation markers into Obsidian footnote syntax.
    footnotes = convert_citations_to_footnotes(soup)

    return soup, footnotes


def convert_citations_to_footnotes(soup: BeautifulSoup) -> list[tuple[str, str]]:
    """
    Replace each inline citation marker with "[^N]" and pull the matching
    reference-list entry text so it can be appended as "[^N]: text".
    Returns an ordered list of (number, text) pairs.
    """
    footnotes: list[tuple[str, str]] = []
    seen_numbers: set[str] = set()

    note_text_by_id: dict[str, str] = {}
    for li in soup.find_all("li", id=re.compile(r"^cite_note-")):
        text = li.get_text(" ", strip=True)
        text = re.sub(r"^\^\s*", "", text)
        note_text_by_id[li["id"]] = text

    for sup in soup.find_all("sup", class_="reference"):
        link = sup.find("a", href=re.compile(r"^#cite_note-"))
        if not link:
            continue
        note_id = link["href"].lstrip("#")
        marker_text = link.get_text(strip=True)
        num_match = re.search(r"\d+", marker_text)
        number = num_match.group(0) if num_match else str(len(footnotes) + 1)

        if number not in seen_numbers:
            seen_numbers.add(number)
            footnotes.append((number, note_text_by_id.get(note_id, "")))

        sup.replace_with(NavigableString(f"[^{number}]"))

    for el in soup.find_all("ol", class_="references"):
        el.decompose()

    return footnotes


# --------------------------------------------------------------------------
# Markdown conversion
# --------------------------------------------------------------------------

class WikiMarkdownConverter(MarkdownConverter):
    """Tuned markdownify converter for wiki article bodies."""

    def __init__(self, base_url: str, **options):
        self.base_url = base_url  # e.g. https://en.wikibooks.org
        super().__init__(**options)

    def convert_sup(self, el, text, **kwargs):
        return f"{text}" if text else ""

    def convert_span(self, el, text, **kwargs):
        return text

    def convert_a(self, el, text, **kwargs):
        href = el.get("href", "")
        if href.startswith("//"):
            el["href"] = "https:" + href
        elif href.startswith("/"):
            el["href"] = self.base_url + href
        return super().convert_a(el, text, **kwargs)

    def convert_img(self, el, text, **kwargs):
        src = el.get("src", "")
        if src.startswith("//"):
            el["src"] = "https:" + src
        elif src.startswith("/"):
            el["src"] = self.base_url + src
        return super().convert_img(el, text, **kwargs)


def html_to_markdown(soup: BeautifulSoup, base_url: str, footnotes: list[tuple[str, str]] | None = None) -> str:
    converter = WikiMarkdownConverter(base_url, heading_style="ATX", bullets="-", wrap=False)
    md = converter.convert_soup(soup)

    md = re.sub(r"[ \t]+\n", "\n", md)
    md = re.sub(r"\n{3,}", "\n\n", md)
    md = md.strip() + "\n"

    if footnotes:
        ordered = sorted(footnotes, key=lambda pair: int(pair[0]))
        footnote_block = "\n".join(f"[^{num}]: {text}" for num, text in ordered if text)
        if footnote_block:
            md += "\n" + footnote_block + "\n"

    return md


