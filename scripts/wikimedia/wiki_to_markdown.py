def write_results_log(log_path: Path, meta: dict, written, skipped_exists, skipped_special, errors, warnings) -> None:
    lines = [
        "wiki_to_markdown results log",
        f"Run started : {meta['started']}",
        f"Input file  : {meta['input']}",
        f"Output dir  : {meta['output']}",
        f"Force mode  : {meta['force']}",
        f"URLs in file: {meta['total']}",
        f"Processed   : {meta['processed']}" + ("  (run was interrupted)" if meta["interrupted"] else ""),
        "",
        "SUMMARY",
        f"  Written (new files)        : {len(written)}",
        f"  Skipped (file exists)      : {len(skipped_exists)}",
        f"  Skipped (Special: pages)   : {len(skipped_special)}",
        f"  Errors                     : {len(errors)}",
        f"  Warnings                   : {len(warnings)}",
        "",
        f"SUCCESSFUL: WRITTEN ({len(written)})",
    ]
    lines += [f"  {url}\n    -> {fname}  ({detail})" for url, fname, detail in written] or ["  (none)"]

    lines += ["", f"SUCCESSFUL: SKIPPED, FILE ALREADY EXISTS ({len(skipped_exists)})"]
    lines += [f"  {url}\n    -> {fname}" for url, fname in skipped_exists] or ["  (none)"]

    lines += ["", f"SKIPPED ON PURPOSE: SPECIAL PAGES ({len(skipped_special)})"]
    lines += [f"  {url}" for url in skipped_special] or ["  (none)"]

    lines += ["", f"ERRORS ({len(errors)})"]
    lines += [f"  {url}\n    {err}" for url, err in errors] or ["  (none)"]

    lines += ["", f"WARNINGS ({len(warnings)})"]
    lines += [f"  {url}\n    {msg}" for url, msg in warnings] or ["  (none)"]

    lines.append("")
    log_path.write_text("\n".join(lines), encoding="utf-8")


# --------------------------------------------------------------------------
# Main pipeline
# --------------------------------------------------------------------------

def find_existing(output_dir: Path, filename: str):
    """Path of `filename` anywhere under output_dir (sort_markdown.py may have moved it into a subfolder), else None."""
    direct = output_dir / filename
    if direct.exists():
        return direct
    if not output_dir.exists():
        return None
    return next(output_dir.rglob(glob.escape(filename)), None)


def process_url(url: str, output_dir: Path, force: bool = False):
    """
    Returns a dict:
      status   : "written" or "exists"
      filename : output file name
      detail   : short text for the log
      fetched  : True if the network was used (controls the polite delay)
      warnings : list of warning strings
    Raises SkipUrl for Special: pages; any other exception is an error.
    """
    host, title = parse_wiki_url(url)
    check_not_special(title)

    suffix = file_suffix(host)
    base_url = f"https://{host}"

    # Cheap pre-check from the URL's own title: skip before any network call.
    guess_name = obsidian_safe_filename(title) + suffix + ".md"
    if not force and find_existing(output_dir, guess_name):
        print(f"skip (exists): {guess_name}")
        return {"status": "exists", "filename": guess_name, "detail": "", "fetched": False, "warnings": []}

    html, raw_categories, display_title = fetch_full_html(host, title)

    filename = obsidian_safe_filename(display_title) + suffix + ".md"
    existing = find_existing(output_dir, filename)
    out_path = existing or (output_dir / filename)  # --force overwrites in place, even inside a sorted subfolder

    # Second check: the real title can differ from the URL title (redirects, casing).
    if existing and not force:
        print(f"skip (exists): {filename}")
        return {"status": "exists", "filename": filename, "detail": "", "fetched": True, "warnings": []}

    warnings = []
    description, desc_ok = fetch_description(host, title)
    if not desc_ok:
        warnings.append("description lookup failed (rate limit or network); description left blank")

    soup, footnotes = uncollapse_and_clean(html, base_url, keep_navboxes=KEEP_NAVBOXES)
    body_md = html_to_markdown(soup, base_url, footnotes)

    categories = filter_categories(raw_categories)
    tags = build_tags(categories)
    word_count = len(re.findall(r"\w+", body_md))
    if word_count == 0:
        warnings.append("0 words in body; file is effectively empty")

    canonical_url = f"https://{host}/wiki/{title.replace(' ', '_')}"

    meta = {
        "title": sentence_case(display_title),
        "description": description or "",
        "source": canonical_url,
        "categories": categories,
        "tags": tags,
        "retrieved": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        "word_count": word_count,
    }

    content = yaml_frontmatter(meta) + f"# {sentence_case(display_title)}\n\n" + body_md

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding="utf-8")
    detail = f"{word_count} words, {len(categories)} categories"
    print(f"wrote: {filename}  ({detail})")
    return {"status": "written", "filename": filename, "detail": detail, "fetched": True, "warnings": warnings}


def main():
    parser = argparse.ArgumentParser(description="Pull full wiki articles into frontmatter-rich markdown.")
    parser.add_argument("--input", default="urls.txt", help="Path to file of wiki URLs (default: urls.txt)")
    parser.add_argument("--output", default="corpus", help="Output directory (default: corpus)")
    parser.add_argument("--force", action="store_true", help="Re-download and overwrite existing files")
    args = parser.parse_args()

    input_path = Path(args.input)
    output_dir = Path(args.output)

    if not input_path.exists():
        print(f"Input file not found: {input_path}", file=sys.stderr)
        sys.exit(1)

    urls = [
        line.strip()
        for line in input_path.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.strip().startswith("#")
    ]

    if not urls:
        print("No URLs found in input file.", file=sys.stderr)
        sys.exit(1)

    started = datetime.now()
    log_path = Path(f"results-log-{started.strftime('%Y-%m-%d_%H%M%S')}.txt")

    written, skipped_exists, skipped_special, errors, warnings = [], [], [], [], []
    processed = 0
    interrupted = False

    print(f"Processing {len(urls)} URL(s) -> {output_dir}/\n")

    try:
        for i, url in enumerate(urls, 1):
            print(f"[{i}/{len(urls)}] {url}")
            fetched = True
            try:
                result = process_url(url, output_dir, force=args.force)
                fetched = result["fetched"]
                if result["status"] == "written":
                    written.append((url, result["filename"], result["detail"]))
                else:
                    skipped_exists.append((url, result["filename"]))
                for w in result["warnings"]:
                    warnings.append((url, w))
            except SkipUrl as e:
                print(f"  skip: {e}")
                skipped_special.append(url)
                fetched = False
            except Exception as e:
                print(f"  ERROR: {e}", file=sys.stderr)
                errors.append((url, str(e)))
            processed = i
            if fetched and i < len(urls):
                time.sleep(REQUEST_DELAY_SECONDS)
    except KeyboardInterrupt:
        interrupted = True
        print("\nInterrupted. Writing results log for what was processed so far.")
    finally:
        write_results_log(
            log_path,
            {
                "started": started.strftime("%Y-%m-%d %H:%M:%S"),
                "input": str(input_path),
                "output": str(output_dir),
                "force": args.force,
                "total": len(urls),
                "processed": processed,
                "interrupted": interrupted,
            },
            written, skipped_exists, skipped_special, errors, warnings,
        )

    print(
        f"\nDone: {len(written)} written, {len(skipped_exists)} already existed, "
        f"{len(skipped_special)} special pages skipped, {len(errors)} failed."
    )
    print(f"Results log: {log_path}")
    if errors:
        print("\nFailed URLs:")
        for url, err in errors:
            print(f"  - {url}\n    {err}")


if __name__ == "__main__":
    main()
