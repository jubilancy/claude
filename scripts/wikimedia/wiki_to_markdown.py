# Frontmatter engine
# --------------------------------------------------------------------------

STOP_CATEGORY_PATTERNS = [
    r"^Articles ",
    r"^All articles ",
    r"^CS1 ",
    r"^Webarchive template",
    r"^Pages using",
    r"^Wikipedia articles",
    r"^Use \w+ dates",
    r"^Use \w+ English",
    r"^Short description",
    r"^All stub articles",
    r" stubs$",
    r"^Commons category",
    r"^Wikidata",
    r"^Good articles$",
    r"^Featured articles$",
    r"^Articles with",
    r"^Vague or ambiguous",
]


def filter_categories(categories: list[str]) -> list[str]:
    """Drop housekeeping/maintenance categories, keep substantive ones."""
    keep = []
    for cat in categories:
        if any(re.search(pat, cat, re.I) for pat in STOP_CATEGORY_PATTERNS):
            continue
        keep.append(cat)
    return keep


def slugify_tag(category: str) -> str:
    tag = category.lower()
    tag = re.sub(r"[^\w\s-]", "", tag)
    tag = re.sub(r"[\s_-]+", "-", tag).strip("-")
    return tag


def build_tags(categories: list[str], max_tags: int = 12) -> list[str]:
    tags = [slugify_tag(c) for c in categories]
    tags = [t for t in tags if t]
    seen = set()
    unique = []
    for t in tags:
        if t not in seen:
            seen.add(t)
            unique.append(t)
    return unique[:max_tags]


def sentence_case(title: str) -> str:
    """Force the first character uppercase; leave the rest as the wiki returned it."""
    if not title:
        return title
    return title[0].upper() + title[1:]


def obsidian_safe_filename(title: str, max_len: int = 180) -> str:
    """Make a filename safe across Obsidian/macOS/Windows filesystems."""
    name = sentence_case(title)
    name = unicodedata.normalize("NFC", name)

    replacements = {
        "/": "-", "\\": "-", ":": " - ", "*": "", "?": "",
        '"': "'", "<": "(", ">": ")", "|": "-",
        "#": "", "^": "", "[": "(", "]": ")",
    }
    for bad, good in replacements.items():
        name = name.replace(bad, good)

    name = re.sub(r"\s+", " ", name).strip()
    name = name.rstrip(". ")

    if not name:
        name = "untitled"

    if len(name) > max_len:
        name = name[:max_len].rstrip()

    return name


def yaml_frontmatter(meta: dict) -> str:
    dumped = yaml.dump(
        meta,
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
        width=1000,
    )
    return f"---\n{dumped}---\n\n"


