#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.9"
# ///
"""
wiki_info.py - Wikipedia URLs -> title, url, Wikidata Q-number, AutoDesc description.

What it does:
- Reads wiki URLs from urls.txt (one per line, # comments ok) or from a CSV
  (the column holding the URLs is auto-detected, or pass --column).
- Looks each article up on the wiki it lives on (any language, mobile hosts,
  /wiki/X and /w/index.php?title=X forms, redirects resolved) and reads its
  Wikidata item.
- Adds the AutoDesc embed link (prefilled with the Q-number) plus the generated
  description, as HTML and as Markdown. AutoDesc has no Markdown format of its
  own, so the Markdown is converted from its HTML.
- Skips URLs already in the output CSV BEFORE making any network request
  (use --force to redo them). Skips Special: pages and non-Wikipedia URLs.
- Retries on 429/503, honoring the Retry-After header when present.
- Writes each row as it goes, so an interrupted run keeps its results.
- Writes results-log-{timestamp}.txt in the current folder every run, with
  separate lists for written, skipped, and errors, plus warnings.

Usage:
    uv run scripts/wikimedia/wiki_info.py                       # reads ./urls.txt, writes ./wiki-info.csv
    uv run scripts/wikimedia/wiki_info.py --input links.csv --column link --output out.csv
    uv run scripts/wikimedia/wiki_info.py --mode short          # short AutoDesc descriptions
    uv run scripts/wikimedia/wiki_info.py --md notes.md         # also append a Markdown file
    uv run scripts/wikimedia/wiki_info.py --no-desc             # title/url/Q only, no AutoDesc calls
    uv run scripts/wikimedia/wiki_info.py --force               # redo URLs already in the output
"""

import argparse
import csv
import html
import io
import json
import re
import sys
import time
import urllib.error
import urllib.parse as up
import urllib.request as ur
from datetime import datetime
from pathlib import Path

USER_AGENT = "wiki-info/1.0 (personal bookmark tooling)"
REQUEST_DELAY_SECONDS = 0.5  # polite pause after each URL that hit the network
MAX_RETRIES = 5  # retries on 429/503 before giving up on a request
RETRY_BASE_SECONDS = 5.0  # first backoff wait; doubles each retry
RETRY_MAX_WAIT_SECONDS = 120.0  # cap on any single wait

WIKI_RE = re.compile(r"^([a-z\-]+?)(?:\.m)?\.wikipedia\.org$", re.I)
COLUMNS = ["input_url", "title", "url", "wikidata_id", "wikidata_url", "description_short",
           "autodesc_url", "description_html", "description_md"]


class SkipUrl(Exception):
    """Raised for URLs that should be skipped on purpose (not errors)."""


# --------------------------------------------------------------------------
# HTTP helper with retry
# --------------------------------------------------------------------------

def get_json(url: str, *, timeout: int = 40, max_retries: int = MAX_RETRIES):
    """GET JSON with retry on 429/503. Honors a numeric Retry-After header."""
    delay = RETRY_BASE_SECONDS
    for attempt in range(max_retries + 1):
        try:
            req = ur.Request(url, headers={"User-Agent": USER_AGENT})
            with ur.urlopen(req, timeout=timeout) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code in (429, 503) and attempt < max_retries:
                ra = e.headers.get("Retry-After", "")
                wait = min(float(ra) if ra.isdigit() else delay, RETRY_MAX_WAIT_SECONDS)
                print(f"  HTTP {e.code}, waiting {wait:.0f}s (retry {attempt + 1}/{max_retries})")
                time.sleep(wait)
                delay *= 2
                continue
            raise
        except urllib.error.URLError as e:
            if attempt < max_retries:
                print(f"  network problem ({e.reason}), retrying {attempt + 1}/{max_retries}")
                time.sleep(delay)
                delay *= 2
                continue
            raise


# --------------------------------------------------------------------------
# URL parsing / lookups
# --------------------------------------------------------------------------

def parse_wiki_url(raw: str):
    """Return (lang, title). Raises SkipUrl for non-Wikipedia URLs and Special: pages."""
    raw = raw.strip()
    if "://" not in raw:
        raw = "https://" + raw
    p = up.urlsplit(raw)
    m = WIKI_RE.match(p.netloc.split(":")[0])
    if not m:
        raise SkipUrl("not a Wikipedia article URL")
    lang = m.group(1).lower()
    if p.path.startswith("/wiki/"):
        title = up.unquote(p.path[len("/wiki/"):])
    else:
        q = up.parse_qs(p.query)
        title = q["title"][0] if "title" in q else ""
    title = title.replace("_", " ").strip()
    if not title:
        raise ValueError(f"Could not extract an article title from URL: {raw}")
    if re.match(r"^special:", title, re.I):
        raise SkipUrl("Special: page (generated by MediaWiki, not a real article)")
    return lang, title


def wp_lookup(lang: str, title: str):
    """Return (canonical title, canonical url, qid or None). Raises RuntimeError if missing."""
    qs = up.urlencode({"action": "query", "prop": "pageprops|info", "ppprop": "wikibase_item",
                       "inprop": "url", "titles": title, "redirects": 1,
                       "format": "json", "formatversion": 2})
    j = get_json(f"https://{lang}.wikipedia.org/w/api.php?{qs}")
    if "error" in j:
        raise RuntimeError(f"Wiki API error for '{title}' on {lang}.wikipedia.org: {j['error']}")
    page = j["query"]["pages"][0]
    if page.get("missing") or page.get("invalid"):
        raise RuntimeError(f"page not found: '{title}' on {lang}.wikipedia.org")
    return page["title"], page.get("fullurl", ""), page.get("pageprops", {}).get("wikibase_item")


def autodesc_embed_url(qid: str, lang: str, mode: str) -> str:
    return "https://autodesc.toolforge.org/?" + up.urlencode(
        {"q": qid, "lang": lang, "mode": mode, "links": "wikipedia",
         "format": "html", "redlinks": "reasonator"})


def autodesc(qid: str, lang: str, mode: str):
    """Return (short manual description, generated description as HTML)."""
    qs = up.urlencode({"q": qid, "lang": lang, "mode": mode, "links": "wikipedia",
                       "format": "json", "redlinks": "reasonator"})
    j = get_json(f"https://autodesc.toolforge.org/?{qs}", max_retries=2)
    return j.get("manual_description") or "", j.get("result") or ""


def html_to_md(s: str) -> str:
    s = re.sub(r"<a [^>]*href=['\"]([^'\"]+)['\"][^>]*>(.*?)</a>", r"[\2](\1)", s, flags=re.S)
    s = re.sub(r"</?(b|strong)>", "**", s)
    s = re.sub(r"</?(i|em)>", "*", s)
    s = re.sub(r"<br\s*/?>", "\n", s)
    s = re.sub(r"<[^>]+>", "", s)
    return html.unescape(s).strip()


# --------------------------------------------------------------------------
# Input reading
# --------------------------------------------------------------------------

def read_urls(path: Path, column):
    text = path.read_text(encoding="utf-8-sig")
    lines = [l for l in text.splitlines() if l.strip() and not l.strip().startswith("#")]
    if not lines:
        return []
    first = lines[0]
    looks_csv = "," in first and not first.lstrip().startswith("http")
    if not looks_csv:
        return [l.strip() for l in lines]
    rows = list(csv.reader(io.StringIO("\n".join(lines))))
    header = rows[0]
    if column is not None:
        if column in header:
            idx = header.index(column)
        elif column.isdigit():
            idx = int(column)
        else:
            sys.exit(f"column {column!r} not found; columns are: {header}")
        data = rows[1:]
    else:
        hit = [i for i, h in enumerate(header) if "wikipedia.org" in h]
        if hit:  # no header row; first row is data
            idx, data = hit[0], rows
        else:
            data = rows[1:]
            counts = [sum("wikipedia.org" in (r[i] if i < len(r) else "") for r in data)
                      for i in range(len(header))]
            if not any(counts):
                sys.exit("no column with wikipedia.org URLs found; use --column")
            idx = counts.index(max(counts))
    return [r[idx].strip() for r in data if idx < len(r) and r[idx].strip()]


# --------------------------------------------------------------------------
# Results log
# --------------------------------------------------------------------------

def write_results_log(log_path: Path, meta: dict, written, skipped_exists, skipped_other, errors, warnings) -> None:
    lines = [
        "wiki_info results log",
        f"Run started : {meta['started']}",
        f"Input file  : {meta['input']}",
        f"Output file : {meta['output']}",
        f"AutoDesc    : {meta['mode']}",
        f"Force mode  : {meta['force']}",
        f"URLs in file: {meta['total']}",
        f"Processed   : {meta['processed']}" + ("  (run was interrupted)" if meta["interrupted"] else ""),
        "",
        "SUMMARY",
        f"  Written (new rows)                    : {len(written)}",
        f"  Skipped (already in output)           : {len(skipped_exists)}",
        f"  Skipped (Special: / non-Wikipedia)    : {len(skipped_other)}",
        f"  Errors                                : {len(errors)}",
        f"  Warnings                              : {len(warnings)}",
        "",
        f"SUCCESSFUL: WRITTEN ({len(written)})",
    ]
    lines += [f"  {url}\n    -> {label}  ({detail})" for url, label, detail in written] or ["  (none)"]

    lines += ["", f"SUCCESSFUL: SKIPPED, ALREADY IN OUTPUT ({len(skipped_exists)})"]
    lines += [f"  {url}" for url in skipped_exists] or ["  (none)"]

    lines += ["", f"SKIPPED ON PURPOSE: SPECIAL PAGES AND NON-WIKIPEDIA URLS ({len(skipped_other)})"]
    lines += [f"  {url}\n    {why}" for url, why in skipped_other] or ["  (none)"]

    lines += ["", f"ERRORS ({len(errors)})"]
    lines += [f"  {url}\n    {err}" for url, err in errors] or ["  (none)"]

    lines += ["", f"WARNINGS ({len(warnings)})"]
    lines += [f"  {url}\n    {msg}" for url, msg in warnings] or ["  (none)"]

    lines.append("")
    log_path.write_text("\n".join(lines), encoding="utf-8")


# --------------------------------------------------------------------------
# Main pipeline
# --------------------------------------------------------------------------

def process_url(url: str, mode: str, no_desc: bool):
    """
    Returns a dict:
      row      : output row (dict)
      detail   : short text for the log
      warnings : list of warning strings
    Raises SkipUrl for Special:/non-Wikipedia URLs; any other exception is an error.
    """
    lang, title = parse_wiki_url(url)
    canon_title, canon_url, qid = wp_lookup(lang, title)

    warnings = []
    row = {"input_url": url, "title": canon_title, "url": canon_url, "wikidata_id": qid or ""}
    if not qid:
        warnings.append("page has no Wikidata item; no description generated")
    else:
        row["wikidata_url"] = "https://www.wikidata.org/wiki/" + qid
        row["autodesc_url"] = autodesc_embed_url(qid, lang, mode)
        if not no_desc:
            try:
                short, long_html = autodesc(qid, lang, mode)
                row["description_short"] = short
                row["description_html"] = long_html
                row["description_md"] = html_to_md(long_html)
                if not long_html:
                    warnings.append("AutoDesc returned an empty description")
            except Exception as e:
                warnings.append(f"AutoDesc lookup failed ({e}); description left blank")
    detail = f"{len(row.get('description_md', '').split())} description words"
    return {"row": row, "detail": detail, "warnings": warnings}


def md_section(row: dict) -> str:
    out = f"## [{row['title']}]({row['url']}) ({row['wikidata_id']})\n\n"
    if row.get("description_short"):
        out += f"*{row['description_short']}*\n\n"
    if row.get("description_md"):
        out += row["description_md"] + "\n\n"
    return out


def main():
    ap = argparse.ArgumentParser(description="Wikipedia URLs -> title, url, Wikidata Q, AutoDesc description.")
    ap.add_argument("--input", default="urls.txt", help="URL list or CSV (default: urls.txt)")
    ap.add_argument("--output", default="wiki-info.csv", help="Output CSV (default: wiki-info.csv)")
    ap.add_argument("--column", help="CSV column name or 0-based index holding the URLs")
    ap.add_argument("--mode", choices=["short", "long"], default="long", help="AutoDesc mode (default: long)")
    ap.add_argument("--md", help="Also append a Markdown section per article to this file")
    ap.add_argument("--no-desc", action="store_true", help="Skip AutoDesc calls (title/url/Q only)")
    ap.add_argument("--force", action="store_true", help="Redo URLs already in the output CSV")
    args = ap.parse_args()

    input_path, output_path = Path(args.input), Path(args.output)
    if not input_path.exists():
        print(f"Input file not found: {input_path}", file=sys.stderr)
        sys.exit(1)
    urls = list(dict.fromkeys(read_urls(input_path, args.column)))
    if not urls:
        print("No URLs found in input file.", file=sys.stderr)
        sys.exit(1)

    done = set()
    if output_path.exists() and not args.force:
        with output_path.open(encoding="utf-8", newline="") as f:
            done = {r["input_url"] for r in csv.DictReader(f)}
    fresh = args.force or not output_path.exists() or output_path.stat().st_size == 0

    started = datetime.now()
    log_path = Path(f"results-log-{started.strftime('%Y-%m-%d_%H%M%S')}.txt")
    written, skipped_exists, skipped_other, errors, warnings = [], [], [], [], []
    processed = 0
    interrupted = False

    print(f"Processing {len(urls)} URL(s) -> {output_path}\n")
    out = output_path.open("w" if fresh else "a", encoding="utf-8", newline="")
    writer = csv.DictWriter(out, COLUMNS, extrasaction="ignore")
    if fresh:
        writer.writeheader()
    md_out = open(args.md, "a", encoding="utf-8") if args.md else None

    try:
        for i, url in enumerate(urls, 1):
            print(f"[{i}/{len(urls)}] {url}")
            fetched = True
            try:
                if url in done:
                    print("skip (already in output)")
                    skipped_exists.append(url)
                    fetched = False
                else:
                    result = process_url(url, args.mode, args.no_desc)
                    row = result["row"]
                    writer.writerow(row)
                    out.flush()
                    if md_out:
                        md_out.write(md_section(row))
                        md_out.flush()
                    label = f"{row['title']} ({row['wikidata_id'] or 'no Q'})"
                    written.append((url, label, result["detail"]))
                    print(f"wrote: {label}  ({result['detail']})")
                    for w in result["warnings"]:
                        print(f"  warning: {w}")
                        warnings.append((url, w))
            except SkipUrl as e:
                print(f"  skip: {e}")
                skipped_other.append((url, str(e)))
                fetched = False
            except Exception as e:
                print(f"  ERROR: {e}", file=sys.stderr)
                errors.append((url, str(e)))
            processed = i
            if fetched and i < len(urls):
                time.sleep(REQUEST_DELAY_SECONDS)
    except KeyboardInterrupt:
        interrupted = True
        print("\nInterrupted. Writing results log for what was processed so far.")
    finally:
        out.close()
        if md_out:
            md_out.close()
        write_results_log(
            log_path,
            {
                "started": started.strftime("%Y-%m-%d %H:%M:%S"),
                "input": str(input_path),
                "output": str(output_path),
                "mode": "off" if args.no_desc else args.mode,
                "force": args.force,
                "total": len(urls),
                "processed": processed,
                "interrupted": interrupted,
            },
            written, skipped_exists, skipped_other, errors, warnings,
        )

    print(
        f"\nDone: {len(written)} written, {len(skipped_exists)} already in output, "
        f"{len(skipped_other)} skipped (Special:/non-Wikipedia), {len(errors)} failed."
    )
    print(f"Results log: {log_path}")
    if errors:
        print("\nFailed URLs:")
        for url, err in errors:
            print(f"  - {url}\n    {err}")


if __name__ == "__main__":
    main()
